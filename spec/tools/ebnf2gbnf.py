#!/usr/bin/env python3
"""Generate spec/grammar.gbnf (llama.cpp / GBNF) from spec/grammar.ebnf, and check it against the examples.

    python3 spec/tools/ebnf2gbnf.py            # write spec/grammar.gbnf
    python3 spec/tools/ebnf2gbnf.py --check    # verify the file is current and every accepted example is derivable

The GBNF grammar is a *superset* of Tez: whitespace and newlines are interchangeable between tokens, and
keywords are not excluded from identifiers (GBNF cannot express either). It is meant to keep a model on
syntactically plausible output; `tez check` is always the judge.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EBNF = ROOT / "spec" / "grammar.ebnf"
GBNF = ROOT / "spec" / "grammar.gbnf"

# lexical rules: name -> (GBNF body, python regex)
LEXICAL = {
    "LOWER": ('[a-z_] [a-zA-Z0-9_]*', r"[a-z_][a-zA-Z0-9_]*"),
    "UPPER": ('[A-Z] [a-zA-Z0-9_]*', r"[A-Z][a-zA-Z0-9_]*"),
    "INT": ('[0-9] [0-9_]*', r"[0-9][0-9_]*"),
    "FLOAT": ('[0-9] [0-9_]* "." [0-9] [0-9_]*', r"[0-9][0-9_]*\.[0-9][0-9_]*"),
    "STRING": ('"\\"" ( [^"\\\\\\n] | "\\\\" ["\\\\ntr0] | "\\\\u{" [0-9a-fA-F]+ "}" )* "\\""',
               r'"(?:[^"\\\n]|\\["\\ntr0]|\\u\{[0-9a-fA-F]+\})*"'),
    "NL": ('"\\n"', r"\n"),
}


def tokenize(text):
    text = re.sub(r"\(\*.*?\*\)", "", text, flags=re.S)
    return re.findall(r'"(?:[^"\\]|\\.)*"|[A-Za-z_][A-Za-z0-9_]*|[=;|{}\[\]()]', text)


def parse(text):
    toks = tokenize(text)
    i = 0
    rules = {}

    def peek():
        return toks[i] if i < len(toks) else None

    def take():
        nonlocal i
        t = toks[i]
        i += 1
        return t

    def alt():
        seqs = [seq()]
        while peek() == "|":
            take()
            seqs.append(seq())
        return ("alt", seqs) if len(seqs) > 1 else seqs[0]

    def seq():
        items = []
        while peek() not in (None, "|", ")", "]", "}", ";"):
            items.append(atom())
        return ("seq", items)

    def atom():
        t = take()
        if t == "(":
            n = alt()
            assert take() == ")"
            return n
        if t == "[":
            n = alt()
            assert take() == "]"
            return ("opt", n)
        if t == "{":
            n = alt()
            assert take() == "}"
            return ("rep", n)
        if t.startswith('"'):
            return ("lit", t[1:-1].replace('\\"', '"').replace("\\\\", "\\"))
        return ("ref", t)

    while peek() is not None:
        name = take()
        assert take() == "=", name
        rules[name] = alt()
        assert take() == ";", name
    return rules


def gname(n):
    return n.lower().replace("_", "-") if n not in LEXICAL else n.lower()


def emit(node, top=True):
    k = node[0]
    if k == "lit":
        s = node[1].replace("\\", "\\\\").replace('"', '\\"')
        return f'"{s}" ws'
    if k == "ref":
        return gname(node[1]) + (" ws" if node[1] in LEXICAL and node[1] != "NL" else "")
    if k == "seq":
        return " ".join(emit(x, False) for x in node[1]) or '""'
    if k == "alt":
        body = " | ".join(emit(x, False) for x in node[1])
        return body if top else f"({body})"
    if k == "opt":
        return f"({emit(node[1])})?"
    if k == "rep":
        return f"({emit(node[1])})*"
    raise ValueError(node)


def generate(rules):
    out = [
        "# Generated by spec/tools/ebnf2gbnf.py from spec/grammar.ebnf. Do not edit.",
        "# A superset of Tez: whitespace is interchangeable between tokens and keywords are not excluded",
        "# from identifiers. `tez check` is the judge; this only keeps generation syntactically plausible.",
        "",
        "root ::= ws file",
        'ws ::= ([ \\t\\n\\r] | "//" [^\\n]*)*',
    ]
    for name, node in rules.items():
        out.append(f"{gname(name)} ::= {emit(node)}")
    for name in ("LOWER", "UPPER", "INT", "FLOAT", "STRING"):
        out.append(f"{gname(name)} ::= {LEXICAL[name][0]}")
    # newlines separate items in Tez, but whitespace is interchangeable here (a superset): `nl` is just whitespace
    out.append("nl ::= ws")
    return "\n".join(out) + "\n"


# ---- recognizer over the EBNF itself (the same relation the GBNF encodes) ----

WS = re.compile(r"(?:[ \t\r\n]|//[^\n]*)*")


def recognizes(rules, src):
    memo = {}
    lex = {k: re.compile(v[1]) for k, v in LEXICAL.items()}

    def skip(p):
        return WS.match(src, p).end()

    def run(node, p):
        k = node[0]
        if k == "lit":
            q = skip(p)
            return {q + len(node[1])} if src.startswith(node[1], q) else set()
        if k == "ref":
            name = node[1]
            if name == "NL":
                return {skip(p)}  # newlines are interchangeable with spaces here
            if name in lex:
                m = lex[name].match(src, skip(p))
                return {m.end()} if m else set()
            key = (name, p)
            if key in memo:
                return memo[key]
            memo[key] = set()  # guards (non-)left recursion
            memo[key] = run(rules[name], p)
            return memo[key]
        if k == "seq":
            cur = {p}
            for x in node[1]:
                nxt = set()
                for q in cur:
                    nxt |= run(x, q)
                cur = nxt
                if not cur:
                    break
            return cur
        if k == "alt":
            r = set()
            for x in node[1]:
                r |= run(x, p)
            return r
        if k == "opt":
            return {p} | run(node[1], p)
        if k == "rep":
            seen, frontier = {p}, {p}
            while frontier:
                new = set()
                for q in frontier:
                    new |= run(node[1], q)
                frontier = new - seen
                seen |= new
            return seen
        raise ValueError(node)

    ends = run(("ref", "file"), 0)
    return len(src) in {skip(e) for e in ends}


def main():
    rules = parse(EBNF.read_text())
    text = generate(rules)
    if "--check" not in sys.argv:
        GBNF.write_text(text)
        print(f"wrote {GBNF.relative_to(ROOT)} ({len(rules)} rules)")
        return
    if GBNF.read_text() != text:
        sys.exit("spec/grammar.gbnf is stale: run python3 spec/tools/ebnf2gbnf.py")
    sys.setrecursionlimit(20000)
    # the generated GBNF itself must derive every accepted example (checked with an independent Earley parser)
    sys.path.insert(0, str(ROOT / "tools" / "gbnf"))
    from earley import Grammar, State

    gram = Grammar(text)
    gbad = []
    for p in sorted((ROOT / "spec" / "examples").glob("*.tez")):
        if p.name.endswith(".reject.tez"):
            continue
        st = State.initial(gram).advance(p.read_text())
        if st is None or not st.complete():
            gbad.append(p.name)
    if gbad:
        sys.exit("spec/grammar.gbnf does not derive: " + ", ".join(gbad))
    bad = []
    n = 0
    for p in sorted((ROOT / "spec" / "examples").glob("*.tez")):
        if p.name.endswith(".reject.tez"):
            continue
        n += 1
        if not recognizes(rules, p.read_text()):
            bad.append(p.name)
    if bad:
        sys.exit("not derivable from the grammar: " + ", ".join(bad))
    print(f"grammar.gbnf is current; {n} accepted examples are derivable")


if __name__ == "__main__":
    main()
